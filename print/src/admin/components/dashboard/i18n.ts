/** Plural bucket: Albanian and English have 1 / many forms ('2' kept so the dictionaries stay uniform). */
export function pluralKey(lang: Lang, n: number): '1' | '2' | '5' {
  void lang;
  return n === 1 ? '1' : '5';
}

/** First letter upper-case (Intl weekday/month names are lower-case in Albanian). */
export const capitalize = (s: string) => (s ? s[0].toLocaleUpperCase() + s.slice(1) : s);

/** Quantity unit after a number: "copë" / "pcs", "set" / "sets". */
export function unitWord(unit: string, n: number, lang: Lang) {
  if (lang === 'en') {
    if (unit === 'set') return n === 1 ? 'set' : 'sets';
    return n === 1 ? 'pc' : 'pcs';
  }
  return unit === 'set' ? 'set' : 'copë';
}
