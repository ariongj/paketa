const spec = (label: L10n, value: L10n | string): ProductSpec => ({ label, value: typeof value === 'string' ? same(value) : value });
const packSpec = (n: number, unit: L10n = T('kom', 'copë', 'pcs')) => spec(L.pack, T(`${n.toLocaleString('de-DE')} ${unit.me}`, `${n.toLocaleString('de-DE')} ${unit.sq}`, `${n.toLocaleString('en-GB')} ${unit.en}`));
const cartonSpec = (packs: number, pieces: number) =>
  spec(L.carton, T(`${packs} pak. · ${pieces.toLocaleString('de-DE')} kom`, `${packs} pako · ${pieces.toLocaleString('de-DE')} copë`, `${packs} packs · ${pieces.toLocaleString('en-GB')} pcs`));
